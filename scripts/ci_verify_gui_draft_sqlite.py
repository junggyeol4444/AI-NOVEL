"""Verify real Windows EXE GUI draft persistence against isolated SQLite, read-only.

Invoked AFTER an external UIAutomation save click. No manuscript, path, or secret
is printed. This script never creates or modifies the database and can only
open a CI-owned SQLite file beneath the per-run temporary QA directory.
"""
from __future__ import annotations

import hashlib
from contextlib import closing
import os
from pathlib import Path
import re
import sqlite3
import sys
from urllib.parse import quote


def verify_sqlite_saved_draft(database: Path, expected_hash: str, runner_temp: Path) -> bool:
    try:
        root = runner_temp.resolve(strict=True)
        path = database.resolve(strict=True)
        if not path.is_file() or path.is_symlink():
            return False
        if not path.is_relative_to(root) or path.parent.parent != root:
            return False
        if not path.parent.name.startswith('anf-korean-gui-'):
            return False
        if path.name != 'only-synthetic.sqlite':
            return False
        if re.fullmatch(r'[0-9a-f]{64}', expected_hash) is None:
            return False
        uri = 'file:' + quote(path.as_posix(), safe='/:') + '?mode=ro'
        with closing(sqlite3.connect(uri, uri=True, timeout=8)) as con:
            con.execute('PRAGMA query_only=ON')
            rows = con.execute(
                "SELECT draft FROM bible_episodes WHERE length(trim(draft)) > 0"
            ).fetchmany(2)
            if len(rows) != 1 or type(rows[0][0]) is not str:
                return False
            manuscript = rows[0][0].replace('\r\n', '\n').replace('\r', '\n')
            actual_hash = hashlib.sha256(manuscript.encode('utf-8')).hexdigest()
            return actual_hash == expected_hash
    except (OSError, ValueError, sqlite3.DatabaseError):
        return False


def export_synthetic_review_sample(database: Path, expected_hash: str,
                                   runner_temp: Path, workspace: Path) -> bool:
    """Export ONLY the verified, fixed-name CI synthetic manuscript.

    A user-chosen DB, output path, or arbitrary local file can never be exported.
    This is an author-created fixture generated by a real offline Windows EXE,
    not a real user manuscript. There is no cloud AI request or publication.
    """
    if not verify_sqlite_saved_draft(database, expected_hash, runner_temp):
        return False
    try:
        root = workspace.resolve(strict=True)
        dest = root / 'build' / 'ci' / 'korean-real-gui' / 'qa_original_scene.txt'
        if dest.is_symlink() or dest.parent.is_symlink():
            return False
        if not dest.resolve(strict=False).is_relative_to(root):
            return False
        db = database.resolve(strict=True)
        uri = 'file:' + quote(db.as_posix(), safe='/:') + '?mode=ro'
        with closing(sqlite3.connect(uri, uri=True, timeout=8)) as con:
            con.execute('PRAGMA query_only=ON')
            rows = con.execute(
                'SELECT draft FROM bible_episodes WHERE length(trim(draft)) > 0'
            ).fetchmany(2)
        if len(rows) != 1 or type(rows[0][0]) is not str:
            return False
        manuscript = rows[0][0].replace('\r\n', '\n').replace('\r', '\n')
        if len(manuscript) > 100_000:
            return False
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(manuscript, encoding='utf-8')
        return True
    except (OSError, ValueError, sqlite3.DatabaseError):
        return False


if __name__ == '__main__':
    path_value = os.environ.get('ANF_QA_SYNTHETIC_DB', '')
    temp_value = os.environ.get('RUNNER_TEMP', '')
    expected = os.environ.get('ANF_QA_EXPECTED_HASH', '')
    okay = bool(path_value and temp_value) and verify_sqlite_saved_draft(
        Path(path_value), expected, Path(temp_value))
    if okay:
        print('ANF_QA_GUI_SQLITE_READ_ONLY_HASH_MATCH')
        workspace = os.environ.get('GITHUB_WORKSPACE', '')
        exported = bool(workspace) and export_synthetic_review_sample(
            Path(path_value), expected, Path(temp_value), Path(workspace))
        if exported:
            print('ANF_QA_SYNTHETIC_ORIGINAL_PROSE_ARTIFACT_READY')
        else:
            print('ANF_QA_SYNTHETIC_PROSE_EXPORT_FAILED')
            okay = False
    else:
        print('ANF_QA_GUI_SQLITE_PERSISTENCE_CHECK_FAILED')
    sys.exit(0 if okay else 1)
